"""Regression tests pinning DailyModel fit & predict outputs."""

import sys

import pytest

from opendsm.eemeter.models.daily.model import DailyModel

from eemeter.perturbations import dst_week_gap, multi_day_gap, negative_export, single_hour_gaps, zeros
from regression_metrics import regression_block



# DailyModel's nlopt SBPLX optimizer lands at a different local minimum on
# Windows. Aggregate sum/mean stay within ~0.05%, but per-bin residual means
# diverge by tens of percent. Pin a Windows-specific snapshot so each platform
# keeps full cell-level regression coverage against itself.
SNAP_SUFFIX = "_win" if sys.platform == "win32" else ""


@pytest.fixture(scope="session")
def daily_baseline_data(comstock_daily_diverse):
    df_b, _ = comstock_daily_diverse

    return df_b.reset_index()


@pytest.fixture(scope="session")
def daily_reporting_data(comstock_daily_diverse):
    _, df_r = comstock_daily_diverse

    return df_r.reset_index()


@pytest.fixture(scope="session")
def daily_model_fit(daily_baseline_data):
    model = DailyModel().fit(
        daily_baseline_data, is_electricity_data=True, enforce_compliance=False
    )

    return model


@pytest.mark.slow
@pytest.mark.regression
def test_daily_baseline_predict_regression(
    daily_model_fit, daily_baseline_data, snapshot
):
    """Fit on baseline -> predict on same data. Catches any change to fit + predict."""
    result = daily_model_fit.predict(daily_baseline_data)

    assert regression_block(result, freq="daily") == snapshot(
        name=f"regression{SNAP_SUFFIX}"
    )


@pytest.mark.slow
@pytest.mark.regression
def test_daily_reporting_predict_regression(
    daily_model_fit, daily_reporting_data, snapshot
):
    """Fit on baseline -> predict on reporting. Catches any change that affects out-of-sample predict."""
    result = daily_model_fit.predict(daily_reporting_data)

    assert regression_block(result, freq="daily") == snapshot(
        name=f"regression{SNAP_SUFFIX}"
    )


FRAME_SCENARIOS = {
    "single_hour_gaps": single_hour_gaps,
    "multi_day_gap": multi_day_gap,
    "zeros": zeros,
    "negative_export": negative_export,
    "dst_week_gap": dst_week_gap,
}

# (scenario, is_electricity_data) -> qualified_name entries expected on
# model.compliance.disqualification after fitting the perturbed baseline. Measured
# by running each scenario against the daily DEFAULT meter with
# enforce_compliance=["model", "settings"]; most perturbations at their default
# intensity don't cross a daily-model sufficiency threshold, so the empty lists
# below are the actual pinned behavior. Negative readings only disqualify gas,
# since net export makes them ordinary for electricity.
FRAME_SCENARIO_DISQUALIFICATIONS = {
    ("single_hour_gaps", True): [],
    ("single_hour_gaps", False): [],
    ("multi_day_gap", True): [],
    ("multi_day_gap", False): [],
    ("zeros", True): [],
    ("zeros", False): [],
    ("negative_export", True): [],
    ("negative_export", False): ["eemeter.sufficiency_criteria.negative_observed_values"],
    ("dst_week_gap", True): [],
    ("dst_week_gap", False): [],
}


@pytest.mark.slow
@pytest.mark.regression
@pytest.mark.parametrize("scenario_name", FRAME_SCENARIOS)
@pytest.mark.parametrize("is_electricity_data", [True, False], ids=["electricity", "gas"])
def test_daily_frame_scenario_regression(
    scenario_name, is_electricity_data, comstock_daily, snapshot
):
    """Perturb the DEFAULT meter's baseline with one frame scenario, fit and predict
    on the perturbed baseline, and snapshot the daily regression block.

    Only `comstock_daily` (the single DEFAULT meter) is used, not the diverse
    fixture, so the scenario grid doesn't multiply by five. The `_win` variants
    for these new cases don't exist yet; they are regenerated by the ops-owned
    three-platform snapshot dispatch, not by this test.
    """
    df_b, df_r = comstock_daily
    baseline, _ = FRAME_SCENARIOS[scenario_name](df_b, df_r, seed=0)
    baseline = baseline.reset_index()

    model = DailyModel().fit(
        baseline,
        is_electricity_data=is_electricity_data,
        enforce_compliance=["model", "settings"],
    )

    expected_disqualifications = FRAME_SCENARIO_DISQUALIFICATIONS[
        (scenario_name, is_electricity_data)
    ]
    disqualified_names = [entry.qualified_name for entry in model.compliance.disqualification]
    assert disqualified_names == expected_disqualifications
    assert model.compliance.qualified == (not expected_disqualifications)

    result = model.predict(baseline, enforce_compliance=["model", "settings"])

    assert regression_block(result, freq="daily") == snapshot(
        name=f"regression{SNAP_SUFFIX}"
    )
